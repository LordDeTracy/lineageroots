    [Fact]
    public void MatchListsAndSharedMatchesImportFromCsv()
    {
        var tester = new Person();
        var list = "﻿Name,Shared cM,Shared Segments,Longest Segment,Match ID\r\n" +
                   "\"Pemberwick, Ada\",\"1,234.5 cM\",31,88.2,A1\r\n" +
                   "Bo Quorrow,212,9,40,B2\r\n" +
                   "No Number,,,,C3\r\n";
        var r = MatchImport.Import(tester, list, "TestCo");
        Assert.Equal((2, 0, 1), (r.Added, r.Updated, r.Problems.Count));
        var ada = tester.DnaMatches.Single(m => m.Name == "Pemberwick, Ada");
        Assert.Equal((1234.5, 31, 88.2, "A1", "TestCo"), (ada.SharedCm, ada.Segments, ada.LongestCm, ada.Reference, ada.Company));

        // Downloading again updates rather than duplicates.
        r = MatchImport.Import(tester, "Name,Shared cM,Match ID\nAda P.,1240,A1\n", "TestCo");
        Assert.Equal((0, 1), (r.Added, r.Updated));
        Assert.Equal(2, tester.DnaMatches.Count);
        Assert.Equal(("Ada P.", 1240.0), (ada.Name, ada.SharedCm));

        r = MatchImport.Import(tester, "Match ID,ICW ID\nA1,B2\nA1,Z9\n");
        Assert.Equal("shared", r.Kind);
        Assert.Equal(1, r.Links);
        Assert.Single(r.Problems);
        var bo = tester.DnaMatches.Single(m => m.Name == "Bo Quorrow");
        Assert.Contains(bo.Id, ada.SharedWith);
        Assert.Contains(ada.Id, bo.SharedWith);

        Assert.Single(MatchImport.Import(tester, "Colour,Size\nred,3\n").Problems);
    }

    [Fact]
    public void TabSeparatedFilesWork()
    {
        var tester = new Person();
        MatchImport.Import(tester, "Display Name\tTotal cM\tLargest Seg\nCy Bellwether\t75\t20\n");
        var m = Assert.Single(tester.DnaMatches);
        Assert.Equal(("Cy Bellwether", 75.0, 20.0), (m.Name, m.SharedCm, m.LongestCm));
    }


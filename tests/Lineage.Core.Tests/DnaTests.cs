    /// <summary>
    /// Regenerates the built-in table (src/Lineage.Core/Dna/CmModelData.cs). Slow, so it only runs when
    /// LINEAGE_GENERATE_CM is set, e.g. LINEAGE_GENERATE_CM=20000 dotnet test --filter RegenerateCmModel.
    /// </summary>
    [Fact]
    public void RegenerateCmModel()
    {
        var setting = Environment.GetEnvironmentVariable("LINEAGE_GENERATE_CM");
        if (string.IsNullOrEmpty(setting)) return;
        var samples = int.TryParse(setting, out var n) && n > 1 ? n : 20000;
        var table = CmModel.Generate(samples, seed: 20261026);
        var dir = AppContext.BaseDirectory;
        while (!File.Exists(Path.Combine(dir, "Lineage.sln")) && Directory.GetParent(dir) is { } up) dir = up.FullName;
        var path = Path.Combine(dir, "src", "Lineage.Core", "Dna", "CmModelData.cs");
        File.WriteAllText(path,
            "namespace Lineage.Core.Dna;\n\n" +
            "/// <summary>Generated by CmModel.Generate — see tests/Lineage.Core.Tests/DnaTests.cs (set LINEAGE_GENERATE_CM). Don't edit by hand.</summary>\n" +
            "internal static class CmModelData\n{\n" +
            $"    // {samples:N0} simulated pairs per relationship.\n" +
            "    public const string Table = \"\"\"\n" + table + "\"\"\";\n}\n");
    }

    private static double Mean(Kinship k, int samples = 400)
    {
        var sim = new Inheritance(12345);
        return Enumerable.Range(0, samples).Average(_ => sim.Simulate(k));
    }

    [Fact]
    public void SimulationMatchesKnownAverages()
    {
        // Averages from large real-world surveys of tested relatives, for comparison.
        Assert.Equal(3485, Mean(new Kinship(1, 0, true), 20), 0);                     // parent: everything
        Assert.InRange(Mean(new Kinship(1, 1, false)), 2500, 2730);                   // full sibling ~2613
        Assert.InRange(Mean(new Kinship(1, 1, true)), 1650, 1850);                    // half sibling ~1750
        Assert.InRange(Mean(new Kinship(2, 0, true)), 1650, 1850);                    // grandparent ~1750
        Assert.InRange(Mean(new Kinship(2, 2, false)), 800, 940);                     // 1st cousin ~866
        Assert.InRange(Mean(new Kinship(3, 3, false)), 190, 270);                     // 2nd cousin ~229
        // Distant cousins: real surveys report more (about 73 cM for 3rd cousins) because they only count pairs
        // who matched and include misreported relationships; the expected inherited share is 3485/64 ≈ 54 cM,
        // less what falls in segments too small to count.
        Assert.InRange(Mean(new Kinship(4, 4, false)), 38, 60);
    }

    [Fact]
    public void KinshipNamesAndDegrees()
    {
        Assert.Equal("parent or child", new Kinship(1, 0, true).Label);
        Assert.Equal("sibling", new Kinship(1, 1, false).Label);
        Assert.Equal("half sibling", new Kinship(1, 1, true).Label);
        Assert.Equal("aunt/uncle or niece/nephew", Kinship.Of(1, 2, false).Label);
        Assert.Equal("2nd great-grandparent", new Kinship(4, 0, true).Label);
        Assert.Equal("1st cousin once removed", Kinship.Of(2, 3, false).Label);
        Assert.Equal("half 3rd cousin", new Kinship(4, 4, true).Label);
        Assert.Equal(-1, new Kinship(1, 1, false).Degree);
        Assert.Equal(new Kinship(2, 0, true).Degree, new Kinship(1, 1, true).Degree);   // grandparent ~ half sibling
        Assert.Equal(new Kinship(2, 2, false).Degree, new Kinship(3, 1, false).Degree); // 1st cousin ~ great-aunt
    }


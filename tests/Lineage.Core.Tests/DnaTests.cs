    [Fact]
    public void MatchesSurviveGedcomAndPrivacyRemovesThem()
    {
        var (t, _, _, _, _, _, boy, girl) = Cousins();
        var a = M(boy, "Wren B", 880.5);
        a.PersonId = girl.Id;
        a.Segments = 30;
        a.LongestCm = 95;
        a.Company = "TestCo";
        a.Reference = "X1";
        a.Note = "Confirmed by letter";
        var b = M(boy, "Unknown cousin", 61);
        Share(a, b);

        var back = GedcomImporter.Import(GedcomExporter.Export(t));
        var boyBack = back.People.Values.Single(p => p.PrimaryName.Given == "Otis");
        var girlBack = back.People.Values.Single(p => p.PrimaryName.Given == "Wren");
        var a2 = boyBack.DnaMatches.Single(m => m.Name == "Wren B");
        Assert.Equal((a.Id, girlBack.Id, 880.5, 30, 95.0, "TestCo", "X1", "Confirmed by letter"),
                     (a2.Id, a2.PersonId!.Value, a2.SharedCm, a2.Segments, a2.LongestCm, a2.Company, a2.Reference, a2.Note));
        Assert.Equal(new[] { b.Id }, a2.SharedWith);

        Assert.All(Privacy.Filter(t, new PrivacyOptions(), 2026).People.Values, p => Assert.Empty(p.DnaMatches));
        Assert.Equal(2, Privacy.Filter(t, new PrivacyOptions { Living = LivingMode.Include }).People[boy.Id].DnaMatches.Count);
    }

    private static Person P(FamilyTree t, string given, string surname, Sex sex)
    {
        var p = t.AddPerson(new Person { Sex = sex });
        p.PrimaryName.Given = given;
        p.PrimaryName.Surname = surname;
        return p;
    }

    private static Family Couple(FamilyTree t, Person? a, Person? b, params Person[] children)
    {
        var f = t.AddFamily(new Family());
        if (a != null) t.SetPartner(f, a, second: false);
        if (b != null) t.SetPartner(f, b, second: true);
        foreach (var c in children) t.AddChild(f, c);
        return f;
    }

    /// <summary>Grandparents with a son (who has a son) and a daughter (who has a daughter). Invented people.</summary>
    private static (FamilyTree T, Person Gran, Person Son, Person SonsWife, Person Daughter, Person DaughtersHusband, Person Boy, Person Girl) Cousins()
    {
        var t = new FamilyTree();
        var gramps = P(t, "Ezra", "Vantreece", Sex.Male);
        var gran = P(t, "Opal", "Hindmarsh", Sex.Female);
        var son = P(t, "Rufus", "Vantreece", Sex.Male);
        var daughter = P(t, "Ida", "Vantreece", Sex.Female);
        Couple(t, gramps, gran, son, daughter);
        var sonsWife = P(t, "Mabel", "Quillfeather", Sex.Female);
        var boy = P(t, "Otis", "Vantreece", Sex.Male);
        Couple(t, son, sonsWife, boy);
        var husband = P(t, "Cyrus", "Bellwether", Sex.Male);
        var girl = P(t, "Wren", "Bellwether", Sex.Female);
        Couple(t, husband, daughter, girl);
        return (t, gran, son, sonsWife, daughter, husband, boy, girl);
    }

    [Fact]
    public void LinksFollowBirthParentsOnly()
    {
        var (t, gran, son, _, daughter, _, boy, girl) = Cousins();
        Assert.Equal(new Kinship(2, 2, false), Placement.Link(t, boy, girl)!.Kinship);          // full 1st cousins
        Assert.Equal(new Kinship(2, 0, true), Placement.Link(t, boy, gran)!.Kinship);
        Assert.Equal(Kinship.Of(1, 2, false), Placement.Link(t, son, girl)!.Kinship);          // uncle
        Assert.Equal(new Kinship(1, 1, false), Placement.Link(t, son, daughter)!.Kinship);

        // An adopted child shares no DNA with the adoptive family.
        var family = t.Family(boy.ParentFamilyIds[0])!;
        family.Children[0].ToFather = ParentRelation.Adopted;
        family.Children[0].ToMother = ParentRelation.Adopted;
        Assert.Null(Placement.Link(t, boy, girl));
    }

    [Fact]
    public void WhatAreTheOddsFindsTheRightBranch()
    {
        var (t, gran, son, sonsWife, daughter, husband, boy, girl) = Cousins();
        // Someone shares 1,750 cM with the grandmother, 880 cM with the boy and 2,600 cM with the girl:
        // that fits a child of the daughter (the girl's full sibling) far better than a child of the son.
        var observations = new[] { new Observation(gran, 1750), new Observation(boy, 880), new Observation(girl, 2600) };
        var hypotheses = new[] { new Hypothesis(son, sonsWife), new Hypothesis(daughter, husband), new Hypothesis(daughter, null) };
        var results = Placement.Evaluate(t, observations, hypotheses);

        Assert.Equal(new Hypothesis(daughter, husband), results[0].Hypothesis);
        Assert.True(results[0].Probability > 0.95);
        Assert.Equal(1, results[0].TimesLessLikely, 6);
        Assert.True(results[1].TimesLessLikely > 100);
        var fit = results[0].Fits.Single(f => f.Observation.Person == girl);
        Assert.Equal("sibling", fit.Relationship);
        Assert.Equal("half sibling", results.Single(r => r.Hypothesis.OtherParent == null).Fits.Single(f => f.Observation.Person == girl).Relationship);
        Assert.Equal("Child of Ida Vantreece and Cyrus Bellwether", results[0].Hypothesis.Label);
    }

    // ---- clustering ----

    private static DnaMatch M(Person tester, string name, double cm)
    {
        var m = new DnaMatch { Name = name, SharedCm = cm };
        tester.DnaMatches.Add(m);
        return m;
    }

    private static void Share(params DnaMatch[] group)
    {
        foreach (var a in group)
            foreach (var b in group)
                if (a != b && !a.SharedWith.Contains(b.Id)) a.SharedWith.Add(b.Id);
    }

    [Fact]
    public void ClustersGroupMatchesThatShareMatches()
    {
        var tester = new Person();
        var north = new[] { M(tester, "Alder", 210), M(tester, "Birch", 150), M(tester, "Cedar", 90), M(tester, "Dogwood", 60) };
        var south = new[] { M(tester, "Elm", 300), M(tester, "Fir", 120), M(tester, "Gum", 45) };
        var loner = M(tester, "Hazel", 80);
        var tooClose = M(tester, "Sister", 2600);
        Share(north);
        Share(south);
        tooClose.SharedWith.AddRange(north.Concat(south).Select(m => m.Id));   // close family match everyone; left out by the cM range
        north[3].SharedWith.Remove(north[2].Id);   // not everyone in a cluster matches everyone
        north[2].SharedWith.Remove(north[3].Id);

        var result = Clusters.Build(tester.DnaMatches);
        Assert.Equal(2, result.Clusters.Count);
        Assert.Equal(new[] { "Alder", "Birch", "Cedar", "Dogwood" }, result.Clusters[0].Members.Select(m => m.Name));
        Assert.Equal(new[] { "Elm", "Fir", "Gum" }, result.Clusters[1].Members.Select(m => m.Name));
        Assert.Equal(new[] { loner }, result.Unclustered);
        Assert.DoesNotContain(tooClose, result.Order);
        Assert.Equal(new[] { 1, 1, 1, 1, 2, 2, 2, 0 }, result.ClusterOf);
        Assert.True(result.Shares(0, 1));
        Assert.False(result.Shares(2, 3));
        Assert.False(result.Shares(0, 4));
    }

    [Fact]
    public void ClusterAncestorsComeFromLinkedMatches()
    {
        var (t, gran, _, _, _, _, boy, girl) = Cousins();
        var a = M(boy, "Wren B", 880);
        a.PersonId = girl.Id;
        var b = M(boy, "Someone else", 60);
        var ancestors = Placement.SharedAncestors(t, boy, new[] { a, b });
        Assert.Contains(ancestors, x => x.AncestorId == gran.Id && x.Count == 1);
        Assert.Equal(2, ancestors.Count);   // both grandparents
    }


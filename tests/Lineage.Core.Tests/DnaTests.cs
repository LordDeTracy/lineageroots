    [Theory]
    [InlineData(3485, 0)]     // parent or child
    [InlineData(2613, -1)]    // full sibling
    [InlineData(1750, 1)]     // grandparent, aunt/uncle, half sibling
    [InlineData(866, 2)]      // 1st cousin, great-grandparent, ...
    [InlineData(430, 3)]      // 1st cousin once removed, half 1st cousin, ...
    [InlineData(220, 4)]      // 2nd cousin, ...
    public void PredictorPutsTypicalSharingInTheRightGroup(double cm, int degree)
    {
        var groups = CmModel.Predict(cm);
        Assert.Equal(degree, groups[0].Degree);
        Assert.Equal(1.0, groups.Sum(g => g.Probability), 6);
        Assert.InRange(groups[0].LowCm, 0, cm);
        Assert.InRange(groups[0].HighCm, cm, 4000);
    }

    [Fact]
    public void ParentAndSiblingAreClearlyApart()
    {
        Assert.True(CmModel.Predict(3450)[0].Probability > 0.9);
        Assert.Contains("parent or child", CmModel.Predict(3450)[0].Label);
        Assert.Contains("sibling", CmModel.Predict(2600)[0].Label);
    }

    [Fact]
    public void DistantCousinsOftenShareNothing()
    {
        Assert.True(CmModel.NoMatchChance(new Kinship(2, 2, false)) < 0.001);   // 1st cousins always match
        Assert.InRange(CmModel.NoMatchChance(new Kinship(6, 6, false)), 0.3, 0.95);   // 5th cousins often don't
        // A relationship further out than the table borrows one with the same expected sharing.
        Assert.Equal(new Kinship(7, 1, false).Degree, CmModel.Nearest(new Kinship(7, 1, false)).Degree);
    }

